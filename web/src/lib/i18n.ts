export function resolveUiLanguage(preference: UiLanguage): "zh" | "en" {
  if (preference === "zh" || preference === "en") return preference;
  return navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
}

export function t(
  key: MessageKey,
  params?: Record<string, string | number>,
  language: "zh" | "en" = "zh"
): string {
  let value: string = (language === "en" ? en : zh)[key] ?? zh[key] ?? key;
  for (const [name, replacement] of Object.entries(params ?? {})) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export function languageName(
  language: { nameZh: string; nameEn: string },
  ui: "zh" | "en"
): string {
  return ui === "en" ? language.nameEn : language.nameZh;
}
